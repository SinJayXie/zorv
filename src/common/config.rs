/// Load server configuration from a TOML file.
///
/// Both read and parse failures are wrapped as [`ZorvError::Config`].
pub fn load_server(path: &str) -> Result<ServerConfig> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| ZorvError::Config(format!("read config {} failed: {}", path, e)))?;
    toml::from_str(&content)
        .map_err(|e| ZorvError::Config(format!("parse config {} failed: {}", path, e)))
}

/// Serialize the server configuration and write it back to a TOML file (for admin
/// UI persistence).
///
/// Uses `toml::to_string_pretty` to produce readable TOML; the original file is
/// overwritten, losing comments and formatting.
pub fn save_server(path: &str, cfg: &ServerConfig) -> Result<()> {
    let content = toml::to_string_pretty(cfg)
        .map_err(|e| ZorvError::Config(format!("serialize config failed: {}", e)))?;
    std::fs::write(path, content)
        .map_err(|e| ZorvError::Config(format!("write config {} failed: {}", path, e)))
}

/// Load client configuration from a TOML file.
///
/// Both read and parse failures are wrapped as [`ZorvError::Config`].
pub fn load_client(path: &str) -> Result<ClientConfig> {
    let content = std::fs::read_to_string(path)
        .map_err(|e| ZorvError::Config(format!("read config {} failed: {}", path, e)))?;
    toml::from_str(&content)
        .map_err(|e| ZorvError::Config(format!("parse config {} failed: {}", path, e)))
}

/// Parse a duration string into whole seconds.
///
/// Supported formats:
/// - `"2s"` → `2`
/// - `"60s"` → `60`
/// - `"500ms"` → `1` (rounded up: `(500+999)/1000`)
/// - `"10"` (bare number) → `10`
///
/// Returns [`ZorvError::Config`] when the string cannot be parsed.
pub fn parse_duration_secs(s: &str) -> Result<u64> {
    let s = s.trim();
    if let Some(num) = s.strip_suffix("ms") {
        let n: u64 = num
            .parse()
            .map_err(|_| ZorvError::Config(format!("invalid duration: {}", s)))?;
        // Round ms up to whole seconds, so e.g. 500ms does not parse to 0.
        Ok(n.div_ceil(1000))
    } else if let Some(num) = s.strip_suffix('s') {
        let n: u64 = num
            .parse()
            .map_err(|_| ZorvError::Config(format!("invalid duration: {}", s)))?;
        Ok(n)
    } else {
        let n: u64 = s
            .parse()
            .map_err(|_| ZorvError::Config(format!("invalid duration: {}", s)))?;
        Ok(n)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_durations() {
        assert_eq!(parse_duration_secs("2s").unwrap(), 2);
        assert_eq!(parse_duration_secs("60s").unwrap(), 60);
        assert_eq!(parse_duration_secs("500ms").unwrap(), 1);
        assert_eq!(parse_duration_secs("1001ms").unwrap(), 2);
        assert_eq!(parse_duration_secs("10").unwrap(), 10);
        assert!(parse_duration_secs("abc").is_err());
    }

    #[test]
    fn server_config_minimal() {
        let toml = r#"
            tunnel_addr = "0.0.0.0:8443"

            [tls]
            cert_file = "cert.pem"
            key_file = "key.pem"

            [auth]
            token = "secret"

            [[proxies]]
            name = "ssh"
            type = "tcp"
            listen = "0.0.0.0:2222"
            client_id = "client-1"
            target = "127.0.0.1:22"
        "#;
        // Verify field mapping via TOML parsing
        let cfg: ServerConfig = toml::from_str(toml).unwrap();
        assert_eq!(cfg.tunnel_addr, "0.0.0.0:8443");
        assert_eq!(cfg.tls.cert_file, "cert.pem");
        assert_eq!(cfg.auth.token, "secret");
        assert!(cfg.auth.allowed_ips.is_none());
        assert_eq!(cfg.proxies.len(), 1);
        assert_eq!(cfg.proxies[0].proxy_type, "tcp");
        assert_eq!(cfg.proxies[0].target, "127.0.0.1:22");
        // Default fields
        assert_eq!(cfg.performance.max_streams_per_tunnel, 1024);
        assert_eq!(cfg.log.level, "info");
        assert!(!cfg.admin.enabled);
        assert_eq!(cfg.admin.listen, "127.0.0.1:9000");
        assert_eq!(cfg.admin.username, "admin");
        assert!(cfg.admin.password.is_empty());
        assert_eq!(cfg.data_dir, "data");
    }

    #[test]
    fn server_config_without_proxies_parses() {
        // First deploy without [[proxies]] must still parse and start
        let toml = r#"
            tunnel_addr = "0.0.0.0:8443"

            [tls]
            cert_file = "cert.pem"
            key_file = "key.pem"

            [auth]
            token = "secret"
        "#;
        let cfg: ServerConfig = toml::from_str(toml).unwrap();
        assert!(cfg.proxies.is_empty());
        assert_eq!(cfg.data_dir, "data");
    }

    #[test]
    fn save_server_roundtrip() {
        let toml = r#"
            tunnel_addr = "0.0.0.0:8443"

            [tls]
            cert_file = "cert.pem"
            key_file = "key.pem"

            [auth]
            token = "secret"

            [[proxies]]
            name = "ssh"
            type = "tcp"
            listen = "0.0.0.0:2222"
            client_id = "client-1"
            target = "127.0.0.1:22"

            [admin]
            enabled = true
            listen = "0.0.0.0:9000"
        "#;
        let cfg: ServerConfig = toml::from_str(toml).unwrap();
        let out = toml::to_string_pretty(&cfg).unwrap();
        let back: ServerConfig = toml::from_str(&out).unwrap();
        assert_eq!(back.tunnel_addr, cfg.tunnel_addr);
        assert_eq!(back.auth.token, cfg.auth.token);
        assert_eq!(back.proxies.len(), 1);
        assert!(back.admin.enabled);
        assert_eq!(back.admin.listen, "0.0.0.0:9000");
    }

    #[test]
    fn client_config_defaults() {
        let toml = r#"
            client_id = "client-1"
            server_addr = "example.com:8443"

            [auth]
            token = "secret"

            [tls]
            # verify_cert should default to true

            [[proxies]]
            name = "ssh"
            type = "tcp"
            target = "127.0.0.1:22"
        "#;
        let cfg: ClientConfig = toml::from_str(toml).unwrap();
        assert_eq!(cfg.client_id, "client-1");
        assert!(cfg.tls.verify_cert);
        assert!(cfg.tls.ca_file.is_none());
        // reconnect defaults
        assert_eq!(cfg.reconnect.initial_delay, "2s");
        assert_eq!(cfg.reconnect.max_delay, "60s");
        assert_eq!(cfg.reconnect.backoff_factor, 2.0);
        assert_eq!(cfg.reconnect.max_retries, 0);
        // listen / client_id are optional on the client side
        assert!(cfg.proxies[0].listen.is_none());
        assert!(cfg.proxies[0].client_id.is_none());
    }

    #[test]
    fn client_config_without_proxies() {
        // proxies are optional in client mode: internal connection targets are
        // configured on the server admin UI.
        let cfg: ClientConfig = toml::from_str(
            r#"
            client_id = "home-nas"
            server_addr = "example.com:8443"

            [auth]
            token = "secret"

            [tls]
            verify_cert = true
        "#,
        )
        .unwrap();
        assert_eq!(cfg.client_id, "home-nas");
        assert!(cfg.proxies.is_empty());
    }

    #[test]
    fn obfuscation_config_defaults() {
        // Defaults: padding off, padding_max=255, heartbeat_jitter on
        let cfg: ClientConfig = toml::from_str(
            r#"
            client_id = "client-1"
            server_addr = "example.com:8443"

            [auth]
            token = "secret"

            [tls]

            [[proxies]]
            name = "ssh"
            type = "tcp"
            target = "127.0.0.1:22"
        "#,
        )
        .unwrap();
        assert!(!cfg.obfuscation.padding);
        assert_eq!(cfg.obfuscation.padding_max, 255);
        assert!(cfg.obfuscation.heartbeat_jitter);
    }

    #[test]
    fn obfuscation_config_parse() {
        let cfg: ClientConfig = toml::from_str(
            r#"
            client_id = "client-1"
            server_addr = "example.com:8443"

            [auth]
            token = "secret"

            [tls]

            [[proxies]]
            name = "ssh"
            type = "tcp"
            target = "127.0.0.1:22"

            [obfuscation]
            padding = true
            padding_max = 512
            heartbeat_jitter = false
        "#,
        )
        .unwrap();
        assert!(cfg.obfuscation.padding);
        assert_eq!(cfg.obfuscation.padding_max, 512);
        assert!(!cfg.obfuscation.heartbeat_jitter);
    }
}
