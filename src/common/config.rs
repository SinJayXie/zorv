/// Authentication configuration, shared by server and client.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AuthConfig {
    /// Shared authentication token.
    pub token: String,
    /// Optional IP allowlist (only enforced on the server side).
    #[serde(default)]
    pub allowed_ips: Option<Vec<String>>,
}

/// A single proxy rule.
///
/// - Server side: `listen` (public listen address) and `client_id` (bound client)
///   are required.
/// - Client side: `listen` / `client_id` are optional; `target` (local target
///   address) is required.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ProxyConfig {
    /// Rule name, used for logging and route matching.
    pub name: String,
    /// Proxy type: `"tcp"` or `"udp"`. Written as `type = "tcp"` in TOML.
    #[serde(rename = "type")]
    pub proxy_type: String,
    /// Server public listen address (required on the server side).
    #[serde(default)]
    pub listen: Option<String>,
    /// Bound client ID (required on the server side).
    #[serde(default)]
    pub client_id: Option<String>,
    /// Local target address on the client side, e.g. `"127.0.0.1:22"`.
    pub target: String,
}

/// Performance tuning parameters.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PerformanceConfig {
    /// Maximum concurrent streams per tunnel, default 1024.
    pub max_streams_per_tunnel: usize,
    /// Per-stream buffer size (bytes), default 256KB = 262144.
    pub stream_buffer_size: usize,
    /// Receive buffer size (bytes), default 1MB = 1048576.
    pub recv_buffer_size: usize,
}

impl Default for PerformanceConfig {
    fn default() -> Self {
        Self {
            max_streams_per_tunnel: 1024,
            stream_buffer_size: 262144,
            recv_buffer_size: 1048576,
        }
    }
}

/// Logging configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LogConfig {
    /// Log level, e.g. `"info"` / `"debug"`.
    pub level: String,
    /// Log output target, e.g. `"stdout"` or a file path such as `"./app.log"`.
    pub output: String,
}

impl Default for LogConfig {
    fn default() -> Self {
        Self {
            level: "info".to_string(),
            output: "./app.log".to_string(),
        }
    }
}

/// Traffic obfuscation configuration (Phase 2, corresponds to product.md 3.6/3.7).
///
/// Defaults keep MVP behavior: random padding off, heartbeat jitter on.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ObfuscationConfig {
    /// Whether to enable random padding to flatten packet-length distribution.
    /// Default off (for low-latency scenarios).
    #[serde(default)]
    pub padding: bool,
    /// Maximum random padding bytes per frame, default 255.
    #[serde(default = "default_padding_max")]
    pub padding_max: usize,
    /// Whether to jitter heartbeat intervals. Default on.
    #[serde(default = "default_heartbeat_jitter_true")]
    pub heartbeat_jitter: bool,
}

fn default_padding_max() -> usize {
    255
}

fn default_heartbeat_jitter_true() -> bool {
    true
}

impl Default for ObfuscationConfig {
    fn default() -> Self {
        Self {
            padding: false,
            padding_max: 255,
            heartbeat_jitter: true,
        }
    }
}

