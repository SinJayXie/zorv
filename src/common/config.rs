//! Zorv configuration definitions and loading.
//!
//! The server config corresponds to `zorvd.toml`, the client config to `zorv.toml`.
//!
//! All structs derive `serde::Deserialize`; optional fields use `#[serde(default)]`
//! so missing TOML keys fall back to the struct's `Default` implementation.

use serde::{Deserialize, Serialize};

use crate::common::error::{Result, ZorvError};

// ---------------------------------------------------------------------------
// Server configuration (zorvd.toml)
// ---------------------------------------------------------------------------

/// Server root configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ServerConfig {
    /// Tunnel listen address, e.g. `"0.0.0.0:8443"`.
    pub tunnel_addr: String,
    /// Paths to the TLS certificate and private key.
    pub tls: ServerTlsConfig,
    /// Authentication configuration (shared token + optional IP allowlist).
    pub auth: AuthConfig,
    /// Proxy rule list (optional).
    ///
    /// The server can start without any rules on first deploy; rules can then be
    /// added dynamically from the admin UI and persisted back to the config file.
    #[serde(default)]
    pub proxies: Vec<ProxyConfig>,
    /// Performance tuning parameters; defaults to [`PerformanceConfig::default`].
    #[serde(default)]
    pub performance: PerformanceConfig,
    /// Logging configuration; defaults to [`LogConfig::default`].
    #[serde(default)]
    pub log: LogConfig,
    /// Traffic obfuscation configuration; defaults to [`ObfuscationConfig::default`].
    #[serde(default)]
    pub obfuscation: ObfuscationConfig,
    /// Web admin UI configuration; defaults to [`AdminConfig::default`] (disabled).
    #[serde(default)]
    pub admin: AdminConfig,
    /// Data directory (where persistent files such as traffic stats are stored,
    /// created automatically); defaults to `"data"`.
    #[serde(default = "default_data_dir")]
    pub data_dir: String,
    /// Event notification configuration (e.g. client-offline alert webhook);
    /// disabled by default.
    #[serde(default)]
    pub notify: NotifyConfig,
}

/// Event notification configuration.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct NotifyConfig {
    /// Webhook URL for client-offline notifications (http/https, POST JSON
    /// `{"client_id":"...","event":"offline"}`).
    #[serde(default)]
    pub webhook: Option<String>,
}

fn default_data_dir() -> String {
    "data".to_string()
}

/// Server web admin UI configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AdminConfig {
    /// Whether the admin UI is enabled. Defaults to `false`.
    #[serde(default)]
    pub enabled: bool,
    /// Admin UI listen address; defaults to `"127.0.0.1:9000"` (local access only).
    #[serde(default = "default_admin_listen")]
    pub listen: String,
    /// Admin UI login username; defaults to `"admin"`.
    #[serde(default = "default_admin_username")]
    pub username: String,
    /// Admin UI login password. Defaults to an empty string; when empty, **login is
    /// disabled** (requests are let through). Supports plaintext or a
    /// PBKDF2-HMAC-SHA256 hash (`$pbkdf2-sha256$...` prefix, generated by
    /// `zorvd hash-password`).
    #[serde(default)]
    pub password: String,
    /// Optional TLS configuration for the admin UI. When set, the admin UI is
    /// served over HTTPS; defaults to plain HTTP.
    #[serde(default)]
    pub tls: Option<AdminTlsConfig>,
}

/// Admin UI HTTPS configuration (optional).
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct AdminTlsConfig {
    pub cert_file: String,
    pub key_file: String,
}

fn default_admin_listen() -> String {
    "127.0.0.1:9000".to_string()
}

fn default_admin_username() -> String {
    "admin".to_string()
}

impl Default for AdminConfig {
    fn default() -> Self {
        Self {
            enabled: false,
            listen: "127.0.0.1:9000".to_string(),
            username: "admin".to_string(),
            password: String::new(),
            tls: None,
        }
    }
}

/// Server TLS configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ServerTlsConfig {
    /// PEM certificate file path.
    pub cert_file: String,
    /// PEM private key file path.
    pub key_file: String,
}

// ---------------------------------------------------------------------------
// Client configuration (zorv.toml)
// ---------------------------------------------------------------------------

/// Client root configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ClientConfig {
    /// Unique client identifier, used for server-side routing binding.
    pub client_id: String,
    /// Server tunnel address, e.g. `"host:8443"`.
    pub server_addr: String,
    /// Authentication configuration (must match the server token).
    pub auth: AuthConfig,
    /// Client TLS configuration.
    pub tls: ClientTlsConfig,
    /// Client proxy rule list (optional).
    ///
    /// The client no longer needs to declare proxy rules: forwarding targets are
    /// configured on the server admin UI, and the server delivers the target in
    /// the `STREAM_OPEN` frame for the client to connect to the local destination.
    #[serde(default)]
    pub proxies: Vec<ProxyConfig>,
    /// Reconnect parameters; defaults to [`ReconnectConfig::default`].
    #[serde(default)]
    pub reconnect: ReconnectConfig,
    /// Logging configuration; defaults to [`LogConfig::default`].
    #[serde(default)]
    pub log: LogConfig,
    /// Traffic obfuscation configuration; defaults to [`ObfuscationConfig::default`].
    #[serde(default)]
    pub obfuscation: ObfuscationConfig,
}

/// Client TLS configuration.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ClientTlsConfig {
    /// Whether to verify the server certificate. Defaults to `true`; can be
    /// disabled for self-signed setups (testing only).
    #[serde(default = "default_verify_cert_true")]
    pub verify_cert: bool,
    /// Custom CA file path. Required when `verify_cert=true`.
    #[serde(default)]
    pub ca_file: Option<String>,
}

fn default_verify_cert_true() -> bool {
    true
}

impl Default for ClientTlsConfig {
    fn default() -> Self {
        Self {
            verify_cert: true,
            ca_file: None,
        }
    }
}

/// Reconnect backoff parameters.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ReconnectConfig {
    /// Initial backoff delay, e.g. `"2s"`.
    pub initial_delay: String,
    /// Maximum backoff delay, e.g. `"60s"`.
    pub max_delay: String,
    /// Backoff multiplier; each reconnect does `delay *= backoff_factor`.
    pub backoff_factor: f64,
    /// Maximum retry count. `0` means retry forever.
    pub max_retries: u32,
}

impl Default for ReconnectConfig {
    fn default() -> Self {
        Self {
            initial_delay: "2s".to_string(),
            max_delay: "60s".to_string(),
            backoff_factor: 2.0,
            max_retries: 0,
        }
    }
}

// ---------------------------------------------------------------------------
// Shared sub-configurations
